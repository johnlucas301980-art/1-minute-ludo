-- 0017_create_country_access_table.sql
-- Country access control system (Phase 1 & 5).
-- Allows admins to enable/disable countries and specific features per country
-- without redeploying the app.

CREATE TABLE IF NOT EXISTS country_access (
  iso2                CHAR(2)      PRIMARY KEY,        -- ISO 3166-1 alpha-2
  name                VARCHAR(100) NOT NULL,
  dial_code           VARCHAR(10)  NOT NULL,
  phone_example       VARCHAR(25)  NOT NULL DEFAULT '',
  is_allowed          BOOLEAN      NOT NULL DEFAULT true,
  allow_registration  BOOLEAN      NOT NULL DEFAULT true,
  allow_login         BOOLEAN      NOT NULL DEFAULT true,
  allow_gameplay      BOOLEAN      NOT NULL DEFAULT true,
  allow_recharge      BOOLEAN      NOT NULL DEFAULT true,
  allow_withdraw      BOOLEAN      NOT NULL DEFAULT true,
  allow_tournament    BOOLEAN      NOT NULL DEFAULT true,
  updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

